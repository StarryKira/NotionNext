function AvatarImage({ src, alt }) {
  const [errored, setErrored] = useState(false)
  if (!src || errored) return <AnthropicMark />
  return (
    <img
      src={src}
      alt={alt || 'avatar'}
      style={{ width: '100%', height: '100%', objectFit: 'cover', borderRadius: '50%', display: 'block' }}
      onError={() => setErrored(true)}
    />
  )
}

export default function AuthorCard() {
  const { siteInfo } = useGlobal()
  const avatar = siteConfig('CLAUDEDOCS_AVATAR_URL', '', CONFIG) || siteInfo?.icon
  const name = siteConfig('AUTHOR') || siteInfo?.author
  const bio = siteConfig('BIO')
  const quote = siteConfig('CLAUDEDOCS_AUTHOR_QUOTE', '', CONFIG)

  const socials = buildSocials({
    github: siteConfig('CONTACT_GITHUB'),
    twitter: siteConfig('CONTACT_TWITTER'),
    email: resolveEmail(siteConfig('CONTACT_EMAIL')),
    telegram: siteConfig('CONTACT_TELEGRAM'),
    linkedin: siteConfig('CONTACT_LINKEDIN'),
    instagram: siteConfig('CONTACT_INSTAGRAM'),
    bilibili: siteConfig('CONTACT_BILIBILI'),
    weibo: siteConfig('CONTACT_WEIBO'),
  })

  return (
    <div className='cd-author-card'>
      <div className='cd-author-avatar'>
        <AvatarImage src={avatar} alt={name} />
      </div>
      {name && <div className='cd-author-name'>{name}</div>}
      {bio && <div className='cd-author-bio'>{bio}</div>}
      {socials.length > 0 && (
        <div className='cd-author-social'>
          {socials.map(s => (
            <a key={s.key} href={s.href} target='_blank' rel='noopener noreferrer'
              aria-label={s.label} title={s.label}>
              <Icon d={ICON_PATHS[s.iconKey]} size={14} />
            </a>
          ))}
        </div>
      )}
      {quote && <div className='cd-author-quote'>"{quote}"</div>}
    </div>
  )
}
