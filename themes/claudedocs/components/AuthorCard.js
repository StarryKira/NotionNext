function buildSocials(opts) {
  const items = []
  const add = (key, href, iconKey, label) => href && items.push({ key, href, iconKey, label })
  add('github', opts.github, 'github', 'GitHub')
  add('twitter', opts.twitter, 'twitter', 'Twitter / X')
  add('email', opts.email && `mailto:${opts.email}`, 'email', 'Email')
  add('telegram', opts.telegram, 'telegram', 'Telegram')
  add('linkedin', opts.linkedin, 'linkedin', 'LinkedIn')
  add('instagram', opts.instagram, 'instagram', 'Instagram')
  add('bilibili', opts.bilibili, 'bilibili', 'Bilibili')
  add('weibo', opts.weibo, 'weibo', 'Weibo')
  return items
}

const resolveEmail = raw => {
  if (!raw || typeof raw !== 'string') return ''
  if (raw.includes('@')) return raw
  try { return decryptEmail(raw) } catch { return '' }
}

